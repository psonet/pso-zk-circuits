    use pso_protocol::witness::{FullProofWitness, HashableNFT, OwnableNFT};

    // -- Test-local NFT that does not depend on any domain crate --

    /// Minimal NFT implementation for circuit testing.
    /// Uses random `entity_hash` since the circuit does not verify the hash formula.
    struct TestNFT {
        ownership: Fr,
        entity_hash: Fr,
    }

    impl OwnableNFT for TestNFT {
        fn ownership(&self) -> Fr {
            self.ownership
        }
    }

    impl HashableNFT for TestNFT {
        fn hash(&self) -> Result<Fr, pso_protocol::ProtocolError> {
            Ok(self.entity_hash)
        }
    }

    /// Create a TestNFT with random crypto data.
    fn make_test_nft() -> (TestNFT, SecretKey, Fr, Vec<MerklePathElement>) {
        let secret_key = {
            let mut b = [0u8; 32];
            OsRng.fill_bytes(&mut b);
            SecretKey::from_slice(&b).expect("random bytes should form a valid key")
        };
        let nonce = Fr::rand(&mut OsRng);

        let ownership = testing::ownership_from_secret_key(&secret_key, nonce).unwrap();
        let entity_hash = Fr::rand(&mut OsRng);

        let merkle_depth = 6;
        let mut merkle_path = Vec::with_capacity(merkle_depth);
        for _ in 0..merkle_depth {
            let random_hash = Fr::rand(&mut OsRng);
            let array = testing::fr_to_le32(&random_hash);

            merkle_path.push(MerklePathElement {
                node_hash: array,
                index: if rand::random() {
                    MerklePathElementIndex::Left
                } else {
                    MerklePathElementIndex::Right
                },
            });
        }

        let nft = TestNFT {
            ownership,
            entity_hash,
        };
        (nft, secret_key, nonce, merkle_path)
    }

