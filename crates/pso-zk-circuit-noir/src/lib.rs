    /// Dumps witness data as a complete Noir `#[test]` function that calls `main()`.
    /// The output can be copy-pasted into `main.nr` to debug circuit failures via `nargo test`.
    fn dump_witness_for_noir_tests(witness: &FullProofWitness) {
        let nonce = FieldElement::from_le_bytes_reduce(&witness.private_inputs.ownership.nonce);
        let expected_ownership =
            FieldElement::from_le_bytes_reduce(&witness.public_inputs.ownership.ownership);
        let nft_hash = FieldElement::from_le_bytes_reduce(&witness.public_inputs.entity_hash);
        let expected_merkle_root =
            FieldElement::from_le_bytes_reduce(&witness.public_inputs.merkle_root);

        fn fmt_bytes(bytes: &[u8]) -> String {
            let items: Vec<String> = bytes.iter().map(|b| format!("{:03}", b)).collect();
            format!("[{}]", items.join(", "))
        }

        let mut sibling_strs: Vec<String> = witness
            .private_inputs
            .merkle_path
            .iter()
            .map(|item| {
                format!(
                    "0x{}",
                    FieldElement::from_le_bytes_reduce(&item.node_hash).to_hex()
                )
            })
            .collect();
        while sibling_strs.len() < SPARSE_MERKLE_PATH_DEPTH {
            sibling_strs.push("0".to_string());
        }

        let mut index_strs: Vec<String> = witness
            .private_inputs
            .merkle_path
            .iter()
            .map(|item| match item.index {
                MerklePathElementIndex::Right => "1".to_string(),
                MerklePathElementIndex::Left => "0".to_string(),
                MerklePathElementIndex::Skip => "0".to_string(),
            })
            .collect();
        while index_strs.len() < SPARSE_MERKLE_PATH_DEPTH {
            index_strs.push("0".to_string());
        }

        println!("// --- Generated Noir test (copy-paste into main.nr) ---");
        println!("#[test]");
        println!("fn test_main_integration() {{");
        println!("    let nonce: Field = 0x{};", nonce.to_hex());
        println!(
            "    let pk_x_bytes: [u8; 32] = {};",
            fmt_bytes(&witness.private_inputs.ownership.public_key_x)
        );
        println!(
            "    let pk_y_bytes: [u8; 32] = {};",
            fmt_bytes(&witness.private_inputs.ownership.public_key_y)
        );
        println!(
            "    let signature: [u8; 64] = {};",
            fmt_bytes(&witness.public_inputs.ownership.signature)
        );
        println!(
            "    let merkle_path_siblings: [Field; 8] = [{}];",
            sibling_strs.join(", ")
        );
        println!(
            "    let merkle_path_indices: [u8; 8] = [{}];",
            index_strs.join(", ")
        );
        println!(
            "    let expected_ownership: Field = 0x{};",
            expected_ownership.to_hex()
        );
        println!("    let nft_hash: Field = 0x{};", nft_hash.to_hex());
        println!(
            "    let expected_merkle_root: Field = 0x{};",
            expected_merkle_root.to_hex()
        );
        println!();
        println!("    main(nonce, pk_x_bytes, pk_y_bytes, signature, merkle_path_siblings, merkle_path_indices, expected_ownership, nft_hash, expected_merkle_root);");
        println!("}}");
        println!("// --- End generated Noir test ---");
    }

    // -- Tests for split_proof() --

    #[test]
    fn test_split_proof_with_multiple_public_inputs() {
        let mut proof = vec![];
        proof.extend_from_slice(&2u32.to_be_bytes()); // 2 public inputs
        proof.extend_from_slice(&[1u8; 32]); // pub_input_0
        proof.extend_from_slice(&[2u8; 32]); // pub_input_1
        proof.extend_from_slice(&[3u8; 100]); // proof bytes

        let (public_inputs, proof_bytes) = split_proof(&proof).unwrap();

        assert_eq!(public_inputs.len(), 2);
        assert_eq!(public_inputs[0], vec![1u8; 32]);
        assert_eq!(public_inputs[1], vec![2u8; 32]);
        assert_eq!(proof_bytes, vec![3u8; 100]);
    }

    #[test]
    fn test_split_proof_with_single_public_input() {
        let mut proof = vec![];
        proof.extend_from_slice(&1u32.to_be_bytes()); // 1 public input
        proof.extend_from_slice(&[4u8; 32]); // pub_input_0
        proof.extend_from_slice(&[5u8; 50]); // proof bytes

        let (public_inputs, proof_bytes) = split_proof(&proof).unwrap();

        assert_eq!(public_inputs.len(), 1);
        assert_eq!(public_inputs[0], vec![4u8; 32]);
        assert_eq!(proof_bytes, vec![5u8; 50]);
    }

    #[test]
    fn test_split_proof_with_no_public_inputs() {
        let mut proof = vec![];
        proof.extend_from_slice(&0u32.to_be_bytes()); // 0 public inputs
        proof.extend_from_slice(&[6u8; 200]); // proof bytes only

        let (public_inputs, proof_bytes) = split_proof(&proof).unwrap();

        assert_eq!(public_inputs.len(), 0);
        assert_eq!(proof_bytes, vec![6u8; 200]);
    }

    #[test]
    fn test_split_proof_too_short_no_prefix() {
        let proof = vec![1u8, 2u8, 3u8]; // Only 3 bytes, need 4+ for count

        let result = split_proof(&proof);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("proof too short"));
    }

    #[test]
    fn test_split_proof_incomplete_public_inputs() {
        let mut proof = vec![];
        proof.extend_from_slice(&2u32.to_be_bytes()); // Claims 2 public inputs
        proof.extend_from_slice(&[1u8; 32]); // Only 1 public input provided
                                             // Missing second public input

        let result = split_proof(&proof);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("invalid proof format"));
    }

    // -- Integration tests (with actual circuits) --

    #[test]
    fn test_full_proof_round_trip() {
        let (nft, secret_key, nonce, merkle_path) = make_test_nft();

        let witness =
            testing::build_full_proof_witness(&nft, &secret_key, nonce, &merkle_path).unwrap();

        let circuit_bytecode = circuit_loader::load_circuit("data/full_proof.json").unwrap();
        let circuit_config = NoirCircuitConfig {
            circuit: circuit_bytecode,
            version: "0.0.1",
            low_memory: false,
            scheme: ZKMode::UltraHonkKeccak,
        };

        let circuit = NoirFullProofCircuit::setup(circuit_config).unwrap();
        let result = circuit.prove(witness.clone());

        if let Err(ref e) = result {
            eprintln!("Prove failed: {e}");
            eprintln!("Dumping witness as Noir test for debugging with `nargo test`:");
            dump_witness_for_noir_tests(&witness);
        }

        let proof = result.unwrap();
        let valid = circuit.verify(proof).unwrap();
        assert!(valid, "Full proof verification failed");
    }

